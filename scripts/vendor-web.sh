#!/usr/bin/env bash
# Vendor the tablet's browser assets into src/jabuka/web/static (laptop, internet, idempotent).
#
#   bash scripts/vendor-web.sh
#
# - npm tarballs fetched with `npm pack --ignore-scripts` (nothing is installed, no install script
#   runs) and verified against the dist.integrity pinned below BEFORE extraction;
# - MapLibre GL JS 5.24.0 (UMD), NoSleep.js 0.12.0, @protomaps/basemaps 5.7.2 (style generator,
#   build time only);
# - Noto Sans glyph ranges and the v4 light/dark sprites from protomaps.github.io/basemaps-assets
#   (MapLibre renders no label offline without them, Pitfall 3);
# - style-day.json / style-night.json generated by scripts/build-styles.mjs;
# - static/vendor/VENDOR.md lists every vendored file with version, source, sha256 and licence.
# Nothing here runs on the Pi and nothing is fetched at runtime.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"
STATIC="$ROOT/src/jabuka/web/static"
CACHE="$ROOT/var/cache/vendor"
ASSETS="https://protomaps.github.io/basemaps-assets"

# name@version  dist.integrity (npm view <pkg>@<ver> dist.integrity)
PKGS=(
    "maplibre-gl@5.24.0 sha512-ALyFxgtd5R+65UqZ/++lOqwWcC0SNho9c27fYSyLmG7AfnAul2o46F05aDJGPbFU57wos9dgcIySHs0Xe6ia3A=="
    "nosleep.js@0.12.0 sha512-9d1HbpKLh3sdWlhXMhU6MMH+wQzKkrgfRkYV0EBdvt99YJfj0ilCJrWRDYG2130Tm4GXbEoTCx5b34JSaP+HhA=="
    "@protomaps/basemaps@5.7.2 sha512-K1Yk6bWdULulYg+R2QRVXx4NzJZan5YQhpejEG0c1/sXruJrfPIPZuakpf3jwAgVmjIRVQwAv+yRafDeN0aaUQ=="
)
FONTS=("Noto Sans Regular" "Noto Sans Medium" "Noto Sans Italic")
RANGES=("0-255" "256-511" "512-767" "8192-8447")
SPRITES=(light light@2x dark dark@2x)

mkdir -p "$CACHE" "$STATIC/vendor" "$STATIC/glyphs" "$STATIC/sprites"

tarball_name() { # name@version -> npm pack file name
    local spec="$1" name ver
    name="${spec%@*}"
    ver="${spec##*@}"
    name="${name#@}"
    echo "${name//\//-}-$ver.tgz"
}

for entry in "${PKGS[@]}"; do
    spec="${entry% *}"
    want="${entry#* }"
    tgz="$CACHE/$(tarball_name "$spec")"
    if [ ! -f "$tgz" ]; then
        echo "vendor-web: npm pack $spec"
        (cd "$CACHE" && npm pack --ignore-scripts --silent "$spec" >/dev/null)
    fi
    got="sha512-$(openssl dgst -sha512 -binary "$tgz" | base64 -w0)"
    if [ "$got" != "$want" ]; then
        echo "vendor-web: INTEGRITY MISMATCH for $spec: $got" >&2
        rm -f "$tgz"
        exit 1
    fi
    dir="$CACHE/${spec//[@\/]/_}"
    rm -rf "$dir" && mkdir -p "$dir"
    tar -xzf "$tgz" -C "$dir"
    echo "vendor-web: $spec verified ($want)"
done

ML="$CACHE/maplibre-gl_5.24.0/package"
NS="$CACHE/nosleep.js_0.12.0/package"
BM="$CACHE/_protomaps_basemaps_5.7.2/package"
cp "$ML/dist/maplibre-gl.js" "$ML/dist/maplibre-gl.css" "$STATIC/vendor/"
cp "$ML/LICENSE.txt" "$STATIC/vendor/LICENSE-maplibre-gl.txt"
cp "$NS/dist/NoSleep.min.js" "$STATIC/vendor/"
cp "$NS/LICENSE" "$STATIC/vendor/LICENSE-nosleep.txt"

fetch() { # url dest
    if [ ! -s "$2" ]; then
        curl -sSfL --retry 3 -o "$2.part" "$1"
        mv "$2.part" "$2"
    fi
}
for font in "${FONTS[@]}"; do
    mkdir -p "$STATIC/glyphs/$font"
    for r in "${RANGES[@]}"; do
        fetch "$ASSETS/fonts/${font// /%20}/$r.pbf" "$STATIC/glyphs/$font/$r.pbf"
    done
done
fetch "https://raw.githubusercontent.com/protomaps/basemaps-assets/main/fonts/OFL.txt" \
    "$STATIC/glyphs/OFL.txt"
for s in "${SPRITES[@]}"; do
    fetch "$ASSETS/sprites/v4/$s.json" "$STATIC/sprites/$s.json"
    fetch "$ASSETS/sprites/v4/$s.png" "$STATIC/sprites/$s.png"
done

node "$ROOT/scripts/build-styles.mjs" "$BM/dist/esm/index.js" "$STATIC"

# -- VENDOR.md ------------------------------------------------------------------------------------
row() { # file version source licence
    local f="$STATIC/$1"
    printf '| `%s` | %s | %s | `%s` | %s |\n' "$1" "$2" "$3" "$(sha256sum "$f" | cut -d' ' -f1)" "$4"
}
{
    echo "# Vendored browser assets"
    echo
    echo "Generated by \`bash scripts/vendor-web.sh\` (laptop, internet, once). npm tarballs are"
    echo "verified against the pinned \`dist.integrity\` before extraction; no install script runs."
    echo "Nothing is fetched at runtime: the tablet loads everything from the core."
    echo
    echo "| npm package | dist.integrity |"
    echo "|---|---|"
    for entry in "${PKGS[@]}"; do echo "| \`${entry% *}\` | \`${entry#* }\` |"; done
    echo
    echo "| File | Version | Source | sha256 | Licence |"
    echo "|---|---|---|---|---|"
    row vendor/maplibre-gl.js 5.24.0 "npm maplibre-gl@5.24.0 dist/" "BSD-3-Clause (LICENSE-maplibre-gl.txt)"
    row vendor/maplibre-gl.css 5.24.0 "npm maplibre-gl@5.24.0 dist/" "BSD-3-Clause"
    row vendor/LICENSE-maplibre-gl.txt 5.24.0 "npm maplibre-gl@5.24.0" "-"
    row vendor/NoSleep.min.js 0.12.0 "npm nosleep.js@0.12.0 dist/" "MIT (LICENSE-nosleep.txt)"
    row vendor/LICENSE-nosleep.txt 0.12.0 "npm nosleep.js@0.12.0" "-"
    for font in "${FONTS[@]}"; do
        for r in "${RANGES[@]}"; do
            row "glyphs/$font/$r.pbf" "basemaps-assets main" "$ASSETS/fonts/" "SIL OFL 1.1 (glyphs/OFL.txt)"
        done
    done
    row glyphs/OFL.txt "basemaps-assets main" "github.com/protomaps/basemaps-assets" "-"
    for s in "${SPRITES[@]}"; do
        row "sprites/$s.json" "sprites v4" "$ASSETS/sprites/v4/" "BSD-3-Clause / CC0 (Protomaps)"
        row "sprites/$s.png" "sprites v4" "$ASSETS/sprites/v4/" "BSD-3-Clause / CC0 (Protomaps)"
    done
    row style-day.json "basemaps 5.7.2" "scripts/build-styles.mjs (flavor light, lang hr)" "BSD-3-Clause (style code)"
    row style-night.json "basemaps 5.7.2" "scripts/build-styles.mjs (flavor black -> red)" "BSD-3-Clause (style code)"
    echo
    echo "Map data: © OpenStreetMap contributors (ODbL 1.0), basemap tiles © Protomaps; shown as"
    echo "\"Protomaps © OpenStreetMap\" in the map attribution."
} >"$STATIC/vendor/VENDOR.md"
echo "vendor-web: ok"

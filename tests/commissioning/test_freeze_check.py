"""scripts/freeze-check.sh (plan 04-02, feature freeze 2026-11-11, T-04-02-04).

Each test builds a small git repository with /usr/bin/git and runs the checker on it with --repo:
F1 clean tree, F2 gate (skipped here), F3/F4 soak reports on code identical to HEAD, F5 reviewed
lock hash in docs/FREEZE.md, F6 wheelhouse built from the frozen source, F7 race-2026 tag at HEAD,
F8 pending UAT items (WARN only), F9 spare SD (HUMAN). Exit 0 when no FAIL.
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
import zipfile
from pathlib import Path

import pytest

from jabuka.soak import report as soak_report

REPO = Path(__file__).resolve().parents[2]
UNIT_NAMES = ("jabuka-core.service", "jabuka-ingest-fastnet.service")
SCRIPT = REPO / "scripts" / "freeze-check.sh"
GIT = "/usr/bin/git"
LINE = re.compile(r"^\[(PASS|FAIL|WARN|SKIP|HUMAN)\] (F\d) (.*)$")
LOCK = """\
# This file was autogenerated by uv
alpha==1.0 \\
    --hash=sha256:00
    # via jabuka
beta-pkg==2.3 \\
    --hash=sha256:11
"""
PLACEHOLDER = "Lock revu : sha256 À REMPLIR"
SCENARIO = '{"name": "race-36h", "seed": 2026, "speed": 60, "duration_s": 129600, "faults": []}\n'


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        [GIT, "-C", str(repo), "-c", "user.name=Test", "-c", "user.email=test@example.invalid",
         "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false", *args],
        check=True, capture_output=True, text=True,
    ).stdout.strip()  # fmt: skip


def commit_all(repo: Path, msg: str) -> str:
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", msg)
    return git(repo, "rev-parse", "HEAD")


def wheel(path: Path, files: dict[str, bytes]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w") as z:
        for name, data in files.items():
            z.writestr(name, data)
    return path


class Frozen:
    """A repo in the frozen state: every check passes (F8 WARN, F9 HUMAN)."""

    def __init__(self, root: Path) -> None:
        self.root = root
        root.mkdir()
        git(root, "init", "-q", "-b", "main")
        self.write(".gitignore", "var/\ndeploy/wheelhouse/\n")
        self.write("pyproject.toml", "[project]\nname = 'jabuka'\n")
        self.write("src/jabuka/__init__.py", "")
        self.write("src/jabuka/core.py", "X = 1\n")
        self.write("src/jabuka/web/static/app.js", "console.log(1)\n")
        self.write("deploy/requirements.lock", LOCK)
        self.write("deploy/PI-SETUP.md", "# setup\n")
        self.write("docs/FREEZE.md", f"# Gel\n\n{PLACEHOLDER}\n")
        self.write(
            ".planning/phases/01-a/01-UAT.md",
            "### 1. x\nresult: [pending]\n### 2. y\nresult: pass\n### 3. z\nresult: [pending]\n",
        )
        for unit in UNIT_NAMES:
            self.write(f"deploy/systemd/{unit}", f"[Service]\nExecStart=/opt/venv/bin/{unit}\n")
        # the race-36h scenario at HEAD that F3/F4 compare the reports with (plan 04-07, CR-01)
        scenario = self.write("src/jabuka/soak/scenarios/race-36h.json", SCENARIO)
        self.scenario_sha = hashlib.sha256(scenario.read_bytes()).hexdigest()
        self.soak_head = commit_all(root, "code")
        self.set_lock_hash()
        self.head = commit_all(root, "lock reviewed")
        self.report("x86_64", self.soak_head)
        # the documented Pi report: `sudo … --systemd system` writes mode systemd and a code
        # block with source "units" (plan 04-06, CR-01)
        self.report(
            "aarch64",
            self.soak_head,
            code=soak_report.code_identity(
                root / "src" / "jabuka", python=None, source="units", units=self.unit_hashes()
            ),
        )
        self.build_wheelhouse()
        git(root, "tag", "-a", "race-2026", "-m", "race")

    def write(self, rel: str, text: str) -> Path:
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        return p

    def lock_sha(self) -> str:
        return hashlib.sha256((self.root / "deploy/requirements.lock").read_bytes()).hexdigest()

    def set_lock_hash(self, value: str | None = None) -> None:
        doc = self.root / "docs/FREEZE.md"
        text = re.sub(
            r"Lock revu : sha256 \S.*", f"Lock revu : sha256 {value or self.lock_sha()}",
            doc.read_text(encoding="utf-8"),
        )  # fmt: skip
        doc.write_text(text, encoding="utf-8")

    def report(self, machine: str, head: str | None, **over: object) -> Path:
        tag = "laptop" if machine == "x86_64" else "pi"
        d = self.root / "var" / "soak" / f"20261110T0{len(machine)}0000Z-race-36h-{tag}"
        d.mkdir(parents=True, exist_ok=True)
        rep = {
            "schema": 1,
            "verdict": "PASS",
            "scenario": "race-36h",
            "mode": "shim" if machine == "x86_64" else "systemd",
            "host": {"machine": machine},
            "git": {"head": head, "dirty": False},
            # a full-length run of the race-36h scenario at HEAD (plan 04-07): sim_s is the real
            # 0fff60c laptop value
            "seed": 2026,
            "sim_s": 129640.6,
            "duration_s": 129600.0,
            "scenario_duration_s": 129600.0,
            "scenario_sha256": self.scenario_sha,
            "skipped": [],
        }
        for k, v in over.items():
            if isinstance(v, dict):
                rep[k] = {**(rep.get(k) or {}), **v}  # type: ignore[dict-item]
            else:
                rep[k] = v
        (d / "report.json").write_text(json.dumps(rep), encoding="utf-8")
        return d / "report.json"

    def pi_copy(self) -> tuple[Path, Path]:
        """What the Pi holds per deploy/PI-SETUP.md §3: an rsync copy of the repo without .git
        (~/jabuka), and the installed package (/opt/jabuka/venv/.../site-packages/jabuka) with
        its compiled files."""
        pi = self.root.parent / "pi"
        checkout = pi / "jabuka"
        shutil.copytree(self.root, checkout, ignore=shutil.ignore_patterns(".git"))
        pkg = pi / "site-packages" / "jabuka"
        shutil.copytree(self.root / "src" / "jabuka", pkg)
        (pkg / "__pycache__").mkdir()
        (pkg / "__pycache__" / "junk.cpython-313.pyc").write_bytes(b"\x00junk")
        return checkout, pkg

    def unit_hashes(self) -> dict[str, str]:
        return {
            u: hashlib.sha256((self.root / "deploy" / "systemd" / u).read_bytes()).hexdigest()
            for u in UNIT_NAMES
        }

    def pi_report(self, pkg: Path, units: dict[str, str] | None = None, **git: object) -> Path:
        code = soak_report.code_identity(
            pkg, python=None, source="units", units=units or self.unit_hashes()
        )
        g = {"head": None, "dirty": None} | git
        return self.report("aarch64", None, git=g, code=code)

    def build_wheelhouse(self, override: dict[str, bytes] | None = None) -> Path:
        wh = self.root / "deploy" / "wheelhouse"
        wheel(wh / "alpha-1.0-py3-none-any.whl", {"alpha/__init__.py": b""})
        wheel(wh / "beta_pkg-2.3-py3-none-any.whl", {"beta_pkg/__init__.py": b""})
        files = {}
        for p in sorted((self.root / "src").rglob("*")):
            if p.is_file():
                files[p.relative_to(self.root / "src").as_posix()] = p.read_bytes()
        files["jabuka-0.1.0.dist-info/METADATA"] = b"Name: jabuka\n"
        files.update(override or {})
        return wheel(wh / "jabuka-0.1.0-py3-none-any.whl", files)

    def check(self, *args: str) -> tuple[int, dict[str, tuple[str, str]], str]:
        proc = subprocess.run(
            ["bash", str(SCRIPT), "--repo", str(self.root), "--skip-gate", *args],
            capture_output=True,
            text=True,
            timeout=120,
            env={"PATH": "/usr/bin:/bin", "GIT": GIT, "HOME": str(self.root)},
        )
        out = proc.stdout + proc.stderr
        items = {}
        for line in proc.stdout.splitlines():
            m = LINE.match(line)
            if m:
                items[m.group(2)] = (m.group(1), m.group(3))
        return proc.returncode, items, out



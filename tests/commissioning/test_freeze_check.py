"""scripts/freeze-check.sh (plan 04-02, feature freeze 2026-11-11, T-04-02-04).

Each test builds a small git repository with /usr/bin/git and runs the checker on it with --repo:
F1 clean tree, F2 gate (skipped here), F3/F4 soak reports on code identical to HEAD, F5 reviewed
lock hash in docs/FREEZE.md, F6 wheelhouse built from the frozen source, F7 race-2026 tag at HEAD,
F8 pending UAT items (WARN only), F9 spare SD (HUMAN). Exit 0 when no FAIL.
"""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
import zipfile
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "scripts" / "freeze-check.sh"
GIT = "/usr/bin/git"
LINE = re.compile(r"^\[(PASS|FAIL|WARN|SKIP|HUMAN)\] (F\d) (.*)$")
LOCK = """\
# This file was autogenerated by uv
alpha==1.0 \\
    --hash=sha256:00
    # via jabuka
beta-pkg==2.3 \\
    --hash=sha256:11
"""
PLACEHOLDER = "Lock revu : sha256 À REMPLIR"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        [GIT, "-C", str(repo), "-c", "user.name=Test", "-c", "user.email=test@example.invalid",
         "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false", *args],
        check=True, capture_output=True, text=True,
    ).stdout.strip()  # fmt: skip


def commit_all(repo: Path, msg: str) -> str:
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", msg)
    return git(repo, "rev-parse", "HEAD")


def wheel(path: Path, files: dict[str, bytes]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w") as z:
        for name, data in files.items():
            z.writestr(name, data)
    return path


class Frozen:
    """A repo in the frozen state: every check passes (F8 WARN, F9 HUMAN)."""

    def __init__(self, root: Path) -> None:
        self.root = root
        root.mkdir()
        git(root, "init", "-q", "-b", "main")
        self.write(".gitignore", "var/\ndeploy/wheelhouse/\n")
        self.write("pyproject.toml", "[project]\nname = 'jabuka'\n")
        self.write("src/jabuka/__init__.py", "")
        self.write("src/jabuka/core.py", "X = 1\n")
        self.write("src/jabuka/web/static/app.js", "console.log(1)\n")
        self.write("deploy/requirements.lock", LOCK)
        self.write("deploy/PI-SETUP.md", "# setup\n")
        self.write("docs/FREEZE.md", f"# Gel\n\n{PLACEHOLDER}\n")
        self.write(
            ".planning/phases/01-a/01-UAT.md",
            "### 1. x\nresult: [pending]\n### 2. y\nresult: pass\n### 3. z\nresult: [pending]\n",
        )
        self.soak_head = commit_all(root, "code")
        self.set_lock_hash()
        self.head = commit_all(root, "lock reviewed")
        self.report("x86_64", self.soak_head)
        self.report("aarch64", self.soak_head)
        self.build_wheelhouse()
        git(root, "tag", "-a", "race-2026", "-m", "race")

    def write(self, rel: str, text: str) -> Path:
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        return p

    def lock_sha(self) -> str:
        return hashlib.sha256((self.root / "deploy/requirements.lock").read_bytes()).hexdigest()

    def set_lock_hash(self, value: str | None = None) -> None:
        doc = self.root / "docs/FREEZE.md"
        text = re.sub(
            r"Lock revu : sha256 \S.*", f"Lock revu : sha256 {value or self.lock_sha()}",
            doc.read_text(encoding="utf-8"),
        )  # fmt: skip
        doc.write_text(text, encoding="utf-8")

    def report(self, machine: str, head: str | None, **over: object) -> Path:
        tag = "laptop" if machine == "x86_64" else "pi"
        d = self.root / "var" / "soak" / f"20261110T0{len(machine)}0000Z-race-36h-{tag}"
        d.mkdir(parents=True, exist_ok=True)
        rep = {
            "schema": 1,
            "verdict": "PASS",
            "scenario": "race-36h",
            "mode": "shim" if machine == "x86_64" else "systemd",
            "host": {"machine": machine},
            "git": {"head": head, "dirty": False},
        }
        for k, v in over.items():
            if isinstance(v, dict):
                rep[k] = {**rep[k], **v}  # type: ignore[dict-item]
            else:
                rep[k] = v
        (d / "report.json").write_text(json.dumps(rep), encoding="utf-8")
        return d / "report.json"

    def build_wheelhouse(self, override: dict[str, bytes] | None = None) -> Path:
        wh = self.root / "deploy" / "wheelhouse"
        wheel(wh / "alpha-1.0-py3-none-any.whl", {"alpha/__init__.py": b""})
        wheel(wh / "beta_pkg-2.3-py3-none-any.whl", {"beta_pkg/__init__.py": b""})
        files = {}
        for p in sorted((self.root / "src").rglob("*")):
            if p.is_file():
                files[p.relative_to(self.root / "src").as_posix()] = p.read_bytes()
        files["jabuka-0.1.0.dist-info/METADATA"] = b"Name: jabuka\n"
        files.update(override or {})
        return wheel(wh / "jabuka-0.1.0-py3-none-any.whl", files)

    def check(self, *args: str) -> tuple[int, dict[str, tuple[str, str]], str]:
        proc = subprocess.run(
            ["bash", str(SCRIPT), "--repo", str(self.root), "--skip-gate", *args],
            capture_output=True,
            text=True,
            timeout=120,
            env={"PATH": "/usr/bin:/bin", "GIT": GIT, "HOME": str(self.root)},
        )
        out = proc.stdout + proc.stderr
        items = {}
        for line in proc.stdout.splitlines():
            m = LINE.match(line)
            if m:
                items[m.group(2)] = (m.group(1), m.group(3))
        return proc.returncode, items, out


@pytest.fixture
def frozen(tmp_path: Path) -> Frozen:
    return Frozen(tmp_path / "repo")


def test_frozen_repo_passes(frozen: Frozen) -> None:
    code, items, out = frozen.check()
    assert code == 0, out
    assert list(items) == [f"F{i}" for i in range(1, 10)], out
    for f in ("F1", "F3", "F4", "F5", "F6", "F7"):
        assert items[f][0] == "PASS", (f, items[f], out)
    assert items["F2"][0] == "SKIP"
    assert items["F8"][0] == "WARN" and "2" in items["F8"][1], items["F8"]
    assert items["F9"][0] == "HUMAN" and "SPARE-SD" in items["F9"][1]


def test_f1_dirty_tree_names_the_file(frozen: Frozen) -> None:
    frozen.write("src/jabuka/core.py", "X = 2\n")
    code, items, out = frozen.check()
    assert code == 1
    assert items["F1"][0] == "FAIL" and "src/jabuka/core.py" in items["F1"][1], out


def test_f3_code_changed_since_the_soak(frozen: Frozen) -> None:
    frozen.write("src/jabuka/core.py", "X = 3\n")
    head = commit_all(frozen.root, "late fix")
    git(frozen.root, "tag", "-f", "-a", "race-2026", "-m", "race", head)
    frozen.build_wheelhouse()
    code, items, out = frozen.check()
    assert code == 1
    assert items["F3"][0] == "FAIL" and "code modifié depuis le soak" in items["F3"][1], out
    assert items["F4"][0] == "FAIL"
    assert items["F1"][0] == "PASS" and items["F6"][0] == "PASS"


def test_f3_doc_change_after_the_soak_is_fine(frozen: Frozen) -> None:
    frozen.write("docs/FREEZE.md", (frozen.root / "docs/FREEZE.md").read_text() + "\nnote\n")
    frozen.write("deploy/PI-SETUP.md", "# setup, reworded\n")
    head = commit_all(frozen.root, "docs")
    git(frozen.root, "tag", "-f", "-a", "race-2026", "-m", "race", head)
    code, items, out = frozen.check()
    assert code == 0, out
    assert items["F3"][0] == "PASS" and items["F4"][0] == "PASS"


def test_f3_f4_missing_dirty_or_failed_reports(frozen: Frozen) -> None:
    for p in (frozen.root / "var" / "soak").glob("*-pi/report.json"):
        p.unlink()
    frozen.report("x86_64", frozen.soak_head, git={"dirty": True})
    code, items, out = frozen.check()
    assert code == 1
    assert items["F3"][0] == "FAIL" and "dirty" in items["F3"][1], out
    assert items["F4"][0] == "FAIL" and "bash scripts/soak.sh" in items["F4"][1], out
    frozen.report("aarch64", frozen.soak_head, verdict="FAIL")
    _, items, out = frozen.check()
    assert items["F4"][0] == "FAIL" and "FAIL" in items["F4"][1], out


def test_f5_lock_hash(frozen: Frozen) -> None:
    frozen.write("docs/FREEZE.md", f"# Gel\n\n{PLACEHOLDER}\n")
    commit_all(frozen.root, "placeholder")
    git(frozen.root, "tag", "-f", "-a", "race-2026", "-m", "race")
    code, items, out = frozen.check()
    assert code == 1
    assert items["F5"][0] == "FAIL" and frozen.lock_sha() in out, out
    frozen.set_lock_hash("0" * 64)
    commit_all(frozen.root, "wrong hash")
    git(frozen.root, "tag", "-f", "-a", "race-2026", "-m", "race")
    _, items, _ = frozen.check()
    assert items["F5"][0] == "FAIL"


def test_f6_wheelhouse_from_the_frozen_source(frozen: Frozen) -> None:
    frozen.build_wheelhouse({"jabuka/core.py": b"X = 99\n"})
    code, items, out = frozen.check()
    assert code == 1
    assert items["F6"][0] == "FAIL" and "jabuka/core.py" in items["F6"][1], out
    frozen.build_wheelhouse()
    (frozen.root / "deploy/wheelhouse/beta_pkg-2.3-py3-none-any.whl").unlink()
    _, items, out = frozen.check()
    assert items["F6"][0] == "FAIL" and "beta" in items["F6"][1], out


def test_f7_tag(frozen: Frozen) -> None:
    git(frozen.root, "tag", "-d", "race-2026")
    code, items, out = frozen.check()
    assert code == 1
    assert items["F7"][0] == "FAIL" and "git tag -a race-2026" in items["F7"][1], out
    code, items, out = frozen.check("--pre")
    assert items["F7"][0] == "SKIP"
    assert code == 0, out


def test_f8_never_fails(frozen: Frozen) -> None:
    lines = "".join(f"### {i}. t\nresult: [pending]\n" for i in range(1, 30))
    frozen.write(".planning/phases/02-b/02-UAT.md", lines)
    commit_all(frozen.root, "uat")
    git(frozen.root, "tag", "-f", "-a", "race-2026", "-m", "race")
    code, items, out = frozen.check()
    assert items["F8"][0] == "WARN" and "31" in items["F8"][1], out
    assert code == 0, out


def test_runs_on_this_repo() -> None:
    """--pre --skip-gate on the real repository: every item is reported. FAILs are expected
    until the owner's freeze on 11 Nov (soak reports, lock hash)."""
    proc = subprocess.run(
        ["bash", str(SCRIPT), "--pre", "--skip-gate"],
        capture_output=True,
        text=True,
        timeout=300,
        cwd=REPO,
    )
    ids = [m.group(2) for m in map(LINE.match, proc.stdout.splitlines()) if m]
    assert ids == [f"F{i}" for i in range(1, 10)], proc.stdout + proc.stderr
    assert proc.returncode in (0, 1)

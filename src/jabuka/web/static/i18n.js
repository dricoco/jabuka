// Tablet UI languages (quick 001): French (source and default), English, Slovenian.
//
//   t(key, params)      the text of key in the current language ({name} placeholders); falls back
//                       to French, then to the key itself (a missing key is visible, never blank)
//   getLang() / setLang(lang)
//                       per device: localStorage "jabuka.lang" (try/catch, the page is plain
//                       http and storage may throw), fr when absent, unknown or unavailable.
//                       No server setting: the helm tablet can be in Slovenian while the owner's
//                       laptop stays in French. Node (the logic tests) has no storage: fr.
//   fmtDec(x, digits)   decimal comma in fr and sl, point in en
//   trServer(text)      the core's French texts (alerts, route reasons, banner) translated on the
//                       client: exact strings, then patterns whose captured reasons are translated
//                       recursively; unknown text is shown as-is, and fr is always the server's
//                       text unchanged (the core's strings stay French: tests depend on them)
//   applyI18n(root)     static markup: data-i18n (text), data-i18n-aria (aria-label),
//                       data-i18n-title (title), data-i18n-ph (placeholder)
//   SERVER              server values the UI compares against (never translated in place)
//
// This is the only static file that holds UI text (tests/test_i18n.py checks it). The Slovenian
// column needs a native speaker's proofreading: docs/I18N-SL-REVIEW.md.


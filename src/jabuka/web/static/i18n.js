export const DICT = { fr: FR, en: EN, sl: SL };

// -- language -----------------------------------------------------------------------------------
const valid = (l) => (LANGS.includes(l) ? l : DEFAULT_LANG);

function readStored() {
  try {
    return valid(globalThis.localStorage?.getItem(STORE_KEY) ?? DEFAULT_LANG);
  } catch {
    return DEFAULT_LANG; // storage blocked (private mode, plain http policy): French
  }
}

let lang = readStored();

export const getLang = () => lang;

// Set (and remember on this device) the language; returns the language applied.
export function setLang(next, { persist = true } = {}) {
  lang = valid(next);
  if (persist) {
    try {
      globalThis.localStorage?.setItem(STORE_KEY, lang);
    } catch {
      /* private mode: this page only */
    }
  }
  const root = globalThis.document?.documentElement;
  if (root) root.lang = lang;
  return lang;
}

export function t(key, params) {
  let s = DICT[lang]?.[key] ?? FR[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, name) => (params[name] === undefined ? m : String(params[name])));
  return s;
}

// x with digits decimals: "0,35" in fr and sl, "0.35" in en.
export function fmtDec(x, digits) {
  const s = x.toFixed(digits);
  return lang === "en" ? s : s.replace(".", ",");
}


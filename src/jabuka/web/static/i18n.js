function trRec(s, depth) {
  if (depth > 4) return s;
  const exact = SRV_EXACT.get(s);
  if (exact) return t(exact);
  for (const [re, key, names] of SRV_RULES) {
    const m = re.exec(s);
    if (!m) continue;
    const params = {};
    names.forEach((n, i) => {
      const v = m[i + 1] ?? "";
      if (n.startsWith("*")) params[n.slice(1)] = trRec(v, depth + 1);
      else params[n] = v;
    });
    return t(`srv.${key}`, params);
  }
  // several reasons joined by the core ("a; b")
  if (s.includes("; ")) return s.split("; ").map((p) => trRec(p, depth + 1)).join("; ");
  return s;
}

// A text produced by the core, in the current language (unknown text: as-is).
export function trServer(text) {
  const s = text === null || text === undefined ? "" : String(text);
  return lang === DEFAULT_LANG ? s : trRec(s, 0);
}

// -- static markup ----------------------------------------------------------------------------------
export function applyI18n(root = globalThis.document) {
  if (!root?.querySelectorAll) return;
  for (const e of root.querySelectorAll("[data-i18n]")) e.textContent = t(e.dataset.i18n);
  for (const e of root.querySelectorAll("[data-i18n-aria]")) e.setAttribute("aria-label", t(e.dataset.i18nAria));
  for (const e of root.querySelectorAll("[data-i18n-title]")) e.setAttribute("title", t(e.dataset.i18nTitle));
  for (const e of root.querySelectorAll("[data-i18n-ph]")) e.setAttribute("placeholder", t(e.dataset.i18nPh));
  const docEl = root.documentElement ?? root.ownerDocument?.documentElement;
  if (docEl) docEl.lang = lang;
}
